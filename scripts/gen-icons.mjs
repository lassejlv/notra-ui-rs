#!/usr/bin/env node
// Regenerates src/icons.rs from assets/icons/*.svg. Add an SVG (24x24 viewBox,
// currentColor paint) to assets/icons and run: node scripts/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "assets/icons");
const files = readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();
const pascal = (s) => s.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const rows = files.map((file) => {
  const stem = file.slice(0, -4);
  const svg = readFileSync(join(dir, file), "utf8");
  const open = svg.match(/<svg([^>]*)>/s);
  const attrs = open[1];
  const view = Number((attrs.match(/viewBox="[\d.\s-]*?\s([\d.]+)"/) || [0, 24])[1]);
  const inherit = ["fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin"]
    .map((name) => {
      const m = attrs.match(new RegExp(`\\s${name}="([^"]*)"`));
      return m ? `${name}="${m[1]}"` : null;
    })
    .filter(Boolean)
    .join(" ");
  const inner = svg.slice(open.index + open[0].length, svg.lastIndexOf("</svg>")).replace(/\s*\n\s*/g, "").trim();
  const body = inherit ? `<g ${inherit}>${inner}</g>` : inner;
  return { stem, variant: pascal(stem), view, body };
});

const out = `//! The icon set Notra's components use, embedded as SVG with \`currentColor\` paint so
//! either renderer can tint them. Generated by \`scripts/gen-icons.mjs\` from
//! \`assets/icons\`: Lucide (ISC), Hugeicons free icons (\`huge-*\`) and brand marks.

/// An embedded SVG icon.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Icon {
${rows.map((r) => `    ${r.variant},`).join("\n")}
}

impl Icon {
    /// Every icon, in file order.
    pub const ALL: &'static [Icon] = &[
${rows.map((r) => `        Icon::${r.variant},`).join("\n")}
    ];

    /// The file stem, e.g. \`"chevron-down"\`.
    pub const fn name(self) -> &'static str {
        match self {
${rows.map((r) => `            Icon::${r.variant} => "${r.stem}",`).join("\n")}
        }
    }

    /// The SVG document.
    pub const fn svg(self) -> &'static str {
        match self {
${rows.map((r) => `            Icon::${r.variant} => include_str!("../assets/icons/${r.stem}.svg"),`).join("\n")}
        }
    }

    /// The SVG body with the root's paint attributes moved onto a group, for
    /// renderers that take a body and a view box (Rune's \`Icon\`).
    pub const fn body(self) -> &'static str {
        match self {
${rows.map((r) => `            Icon::${r.variant} => r#"${r.body}"#,`).join("\n")}
        }
    }

    /// The square view box size.
    pub const fn view_box(self) -> f32 {
        match self {
${rows.map((r) => `            Icon::${r.variant} => ${r.view.toFixed(1)},`).join("\n")}
        }
    }

    /// The asset path GPUI's \`svg().path(..)\` loads through \`notra_ui::gpui::Assets\`.
    pub const fn path(self) -> &'static str {
        match self {
${rows.map((r) => `            Icon::${r.variant} => "notra/icons/${r.stem}.svg",`).join("\n")}
        }
    }

    /// The icon as Rune draws it.
    #[cfg(feature = "rune")]
    pub fn rune(self) -> &'static ::rune::Icon {
        &RUNE_ICONS[self as usize]
    }

    /// Looks an icon up by its file stem.
    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|icon| icon.name() == name)
    }
}

#[cfg(feature = "rune")]
static RUNE_ICONS: &[::rune::Icon] = &[
${rows.map((r) => `    ::rune::Icon { name: "${r.stem}", view: ${r.view.toFixed(1)}, body: r#"${r.body}"# },`).join("\n")}
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_icon_round_trips_by_name() {
        for icon in Icon::ALL {
            assert!(icon.svg().contains("<svg"), "{} is not an svg", icon.name());
            assert!(!icon.body().is_empty());
            assert_eq!(Icon::from_name(icon.name()), Some(*icon));
        }
    }
}
`;
writeFileSync(join(root, "src/icons.rs"), out);
console.log(`${rows.length} icons`);
